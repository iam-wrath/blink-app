"""Export the five challenge targets' cached searches into seed/, so a fresh host shows them without IRSA.

Writes:
  seed/search-cache.json        one entry per search: its query and the API's full response
  seed/cache/frames/<key>/...   only the PNGs those responses use

Run from the repo root with the API running (start.ps1 or `node dist/main.js`):
  py scripts/export_seed.py            (default API: http://localhost:3000)
The API loads seed/search-cache.json on start and serves seed/cache/ as a fallback for /data/cache/.
"""
import json
import os
import shutil
import sys
import urllib.parse
import urllib.request

API = (sys.argv[1] if len(sys.argv) > 1 else "http://localhost:3000").rstrip("/")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEED = os.path.join(ROOT, "seed")


def get(path):
    with urllib.request.urlopen(API + path, timeout=600) as r:
        return json.load(r)


def main():
    targets = get("/api/targets")
    entries, pngs = [], set()
    for t in targets:
        det = t.get("detector", "D2")
        coadds = ["none", "visit"] if t.get("coadd") == "visit" else ["none"]
        for coadd in coadds:
            for mode in ("raw", "diff"):
                q = {"ra": t["ra"], "dec": t["dec"], "fov": t["fov"], "detector": det, "mode": mode, "coadd": coadd}
                resp = get("/api/frames?" + urllib.parse.urlencode(q))
                if not resp.get("frames"):
                    print(f"  skip {t['name']} {mode} {coadd}: no frames")
                    continue
                entries.append({"query": q, "response": resp})
                pngs.update(f["png"] for f in resp["frames"])
                print(f"  {t['name']:15s} {det} {mode:4s} coadd={coadd:5s} {len(resp['frames'])} frames")

    out = os.path.join(SEED, "cache")
    if os.path.isdir(out):
        shutil.rmtree(out)  # seed/cache is generated by this script only
    size = 0
    for png in sorted(pngs):
        rel = png.split("data/cache/", 1)[1]  # frames/<key>/<file>.png
        src = os.path.join(ROOT, "data", "cache", *rel.split("/"))
        dst = os.path.join(out, *rel.split("/"))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
        size += os.path.getsize(dst)
    with open(os.path.join(SEED, "search-cache.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(entries, f, separators=(",", ":"))
    print(f"{len(entries)} searches, {len(pngs)} PNGs, {size / 1e6:.1f} MB -> {SEED}")


if __name__ == "__main__":
    main()
